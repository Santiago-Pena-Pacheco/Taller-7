    private void BtnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnRegistrarActionPerformed
        String tipo = comboTipo.getSelectedItem().toString();
        String codigo = campoCodigo.getText();
        String destinatario = campoDestinatario.getText();
        double peso = Double.parseDouble(campoPeso.getText());

        Envio envio;
        if (tipo.equals("Estandar")) {
            envio = new EnvioEstandar(codigo, destinatario, peso, campoDireccion.getText());
        } else if (tipo.equals("Express")) {
            envio = new EnvioExpress(codigo, destinatario, peso, campoHora.getText());
        } else {
            envio = new EnvioInternacional(codigo, destinatario, peso, campoPais.getText());
        }

        this.registros.agregarEnvio(envio);
        this.actualizarTabla();
        this.mostrarMensaje("Envio registrado con exito");
        this.vaciarCampos();
    }//GEN-LAST:event_BtnRegistrarActionPerformed

    private void comboTipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_comboTipoActionPerformed
        this.mostrarCamposExtra();
    }//GEN-LAST:event_comboTipoActionPerformed

    private void mostrarCamposExtra() {
        String tipo = comboTipo.getSelectedItem().toString();

        lblDireccion.setVisible(tipo.equals("Estandar"));
        campoDireccion.setVisible(tipo.equals("Estandar"));

        lblHora.setVisible(tipo.equals("Express"));
        campoHora.setVisible(tipo.equals("Express"));

        lblPais.setVisible(tipo.equals("Internacional"));
        campoPais.setVisible(tipo.equals("Internacional"));
    }

    private void vaciarCampos() {
        campoCodigo.setText("");
        campoDestinatario.setText("");
        campoPeso.setText("");
        campoDireccion.setText("");
        campoHora.setText("");
        campoPais.setText("");
    }

    private void mostrarMensaje(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje);
    }

    private void actualizarTabla() {
        modeloTabla.setRowCount(0);
        ArrayList<Envio> envios = this.registros.obtenerEnvios();
        for (Envio e : envios) {
            modeloTabla.addRow(new Object[]{e.getCodigo(), e.getDestinatario(), e.getPeso(), e.getTipo(), e.calcularCosto()});
        }
    }

